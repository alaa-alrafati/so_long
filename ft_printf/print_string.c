#include "ft_printf.h"

int	print_string(char *s)
{
	int	x;

	x = 0;
	if (s == NULL)
	{
		write(1, "(null)", 6);
		return (6);
	}
	while (s[x] != '\0')
	{
		write(1, &s[x], 1);
		x++;
	}
	return (x);
}
